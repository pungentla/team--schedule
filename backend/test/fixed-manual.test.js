test('长期名单无需重复报名：周一A、周二B和C，优化不挪动固定人，其他日期不自动扩大报名', () => {
  const first = generate();
  assert.equal(first.assignments.length, 6);
  assert.equal(first.gaps.fixedConflicts.length, 0);
  for (const day of ['2026-11-09','2026-11-16']) assert.deepEqual(first.assignments.filter((a) => a.workDate === day).map((a) => a.userId), [people[0]]);
  for (const day of ['2026-11-10','2026-11-17']) assert.deepEqual(first.assignments.filter((a) => a.workDate === day).map((a) => a.userId).sort(), [people[1],people[2]].sort());
  assert.ok(first.assignments.every((a) => a.isFixed));
  assert.ok(draft().assignments.every((a) => a.isFixed && a.source === 'manual'));
  assert.equal(enrollments.listEnrollments(period).effectiveCount, 3);
  publish(first);
  const second = periods.insertPeriod({ name: '后续两周', startDate: '2026-11-23', endDate: '2026-12-06', status: 'enrolling' });
  periodService.generateSlots(second, { defaultNeed: 0 }, ctx()); periodService.applyWorkRules(second, ctx());
  const next = schedule.generate(second, {}, ctx());
  assert.equal(next.assignments.length, 6);
});
