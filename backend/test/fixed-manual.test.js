test('管理员直接转班立即生效，无需员工确认，并记录实际管理员与修订版本', () => {
  publish(generate());
  const old = live().assignments.find((a) => a.userId === people[0]);
  const payload = { type: 'transfer', fromAssignmentId: old.id, toUserId: people[1], message: '临时调配' };
  assert.throws(() => swaps.reassignByAdmin(payload, ctx(people[0])), (e) => e.status === 403);
  swaps.reassignByAdmin(payload, ctx());
  assert.equal(assignments.findAssignment(old.id).status, 'released');
  assert.equal(live().assignments.find((a) => a.workDate === old.workDate).userId, people[1]);
  assert.equal(live().run.revision, 1);
  assert.equal(live().metrics.workload.distribution.find((u) => u.userId === people[1]).assigned, 3);
  assert.equal(db.pluck('SELECT COUNT(*) FROM swap_requests'), 0);
  assert.equal(db.pluck('SELECT COUNT(*) FROM swap_participants'), 0);
  const log = db.get("SELECT * FROM audit_logs WHERE action='ASSIGNMENT_MANUAL' ORDER BY id DESC");
  assert.ok(log, 'manual audit'); assert.equal(log.actor_id, admin);
  assert.throws(() => swaps.reassignByAdmin(payload, ctx()), (e) => e.code === 'ASSIGNMENT_RELEASED');
});
test('直接交换两个班次保留岗位与人数，约束失败整体回滚；不能调整旧版本或草稿', () => {
  const run = generate(); const draftA = draft().assignments.find((a) => a.userId === people[0]);
  assert.throws(() => swaps.reassignByAdmin({ type: 'transfer', fromAssignmentId: draftA.id, toUserId: people[1] }, ctx()), (e) => e.code === 'ASSIGNMENT_RELEASED');
  publish(run);
  const old = live().assignments;
  const a = old.find((a) => a.userId === people[0]); const b = old.find((a) => a.userId === people[1]);
  swaps.reassignByAdmin({ type: 'exchange', fromAssignmentId: a.id, toUserId: people[1], toAssignmentId: b.id }, ctx());
  assert.equal(live().assignments.length, 6);
  assert.ok(live().assignments.some((x) => x.workDate === a.workDate && x.userId === people[1]));
  assert.ok(live().assignments.some((x) => x.workDate === b.workDate && x.userId === people[0]));
  const after = live().assignments;
  const from = after.find((x) => x.workDate === '2026-11-17' && x.userId === people[1]);
  assert.throws(() => swaps.reassignByAdmin({ type: 'transfer', fromAssignmentId: from.id, toUserId: people[2] }, ctx()), (e) => e.code === 'SWAP_CONFLICT');
  assert.deepEqual(live().assignments, after);
  const next = generate(); const reviewedLive = live().run;
  const one = live().assignments.find((x) => x.userId === people[0] && x.workDate === '2026-11-16');
  swaps.reassignByAdmin({ type: 'transfer', fromAssignmentId: one.id, toUserId: people[2] }, ctx());
  assert.throws(() => schedule.publish(period, next.runId, ctx(), { publishedRunId: reviewedLive.id, publishedRevision: reviewedLive.revision }), (e) => e.code === 'PUBLISHED_CHANGED');
  publish(next);
  assert.throws(() => swaps.reassignByAdmin({ type: 'transfer', fromAssignmentId: from.id, toUserId: people[0] }, ctx()), (e) => e.code === 'ASSIGNMENT_RELEASED');
});
