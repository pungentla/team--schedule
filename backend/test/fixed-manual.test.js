test('草稿可替换、移除及补人，保持其他安排、重新统计、不影响已发布排班', () => {
  publish(generate()); const before = live().assignments;
  const next = generate(); const current = draft().assignments.find((a) => a.userId === people[0]);
  const candidates = schedule.getDraftCandidates(next.runId, { assignmentId: current.id });
  assert.ok(candidates.candidates.find((u) => u.userId === people[1]).canAssign);
  let result = schedule.adjustDraft(next.runId, { action: 'replace', assignmentId: current.id, userId: people[1], revision: 0 }, ctx());
  assert.equal(result.run.revision, 1); assert.equal(result.assignments.length, 6);
  assert.deepEqual(live().assignments, before);
  assert.equal(result.assignments.find((a) => a.workDate === current.workDate).source, 'manual');
  assert.equal(result.assignments.find((a) => a.workDate === current.workDate).isFixed, false);
  assert.throws(() => schedule.publish(period, next.runId, ctx(), { expectedRevision: 0 }), (e) => e.code === 'DRAFT_CHANGED');
  const replace = result.assignments.find((a) => a.workDate === current.workDate);
  result = schedule.adjustDraft(next.runId, { action: 'remove', assignmentId: replace.id, revision: 1 }, ctx());
  assert.equal(result.run.totalFilled, 5);
  result = schedule.adjustDraft(next.runId, { action: 'add', workDate: current.workDate, shiftId: shift, workTypeId: work, dutyRole: 'member', userId: people[2], revision: 2 }, ctx());
  assert.equal(result.run.totalFilled, 6); assert.equal(result.run.revision, 3);
  assert.equal(result.metrics.workload.distribution.reduce((sum,x) => sum + x.assigned,0), 6);
  assert.throws(() => schedule.adjustDraft(next.runId, { action: 'add', workDate: current.workDate, shiftId: shift, workTypeId: work, dutyRole: 'member', userId: people[1] }, ctx()), (e) => e.code === 'DRAFT_CONSTRAINT_VIOLATION');
  assert.throws(() => schedule.adjustDraft(next.runId, { action: 'remove', assignmentId: result.assignments[0].id }, ctx(people[0])), (e) => e.status === 403);
  schedule.publish(period, next.runId, ctx(), { expectedRevision: 3 });
  assert.throws(() => schedule.adjustDraft(next.runId, { action: 'remove', assignmentId: result.assignments[0].id }, ctx()), (e) => e.code === 'DRAFT_LOCKED');
});
